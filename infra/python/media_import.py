"""Fixed-operation local tools. Node owns URL validation, rights and job state."""
import argparse
import json
import os
from pathlib import Path
import wave
import sys


def download(url, directory):
    from yt_dlp import YoutubeDL

    directory = Path(directory)
    limit = 125 * 1024 * 1024

    def bounded(progress):
        if progress.get("downloaded_bytes", 0) > limit:
            raise ValueError("Download exceeds limit")

    class Quiet:
        def debug(self, message):
            pass

        info = debug
        warning = debug
        error = debug

    common = {"noplaylist": True, "quiet": True, "no_warnings": True,
              "logger": Quiet(), "socket_timeout": 20, "retries": 1,
              "fragment_retries": 1, "cachedir": False, "fixup": "never",
              "max_filesize": limit, "progress_hooks": [bounded],
              "overwrites": True}
    video_options = {**common, "format": "bestvideo[ext=mp4][vcodec^=avc1][height<=480]/best[ext=mp4][height<=720]",
                     "outtmpl": str(directory / "video.mp4")}
    with YoutubeDL(video_options) as downloader:
        info = downloader.extract_info(url, download=False)
        if (info.get("_type", "video") != "video" or info.get("is_live") or
                not 0 < (info.get("duration") or 0) <= 1800 or
                info.get("extractor_key", "").lower() not in ("youtube", "tiktok")):
            raise ValueError("Unsupported single video")
        downloader.process_info(info)
    if not (directory / "video.mp4").is_file():
        raise ValueError("Video not downloaded")
    audio_path = "video.mp4"
    if info.get("acodec") == "none":
        with YoutubeDL({**common, "format": "bestaudio[ext=m4a]", "outtmpl": str(directory / "audio.m4a")}) as downloader:
            downloader.extract_info(url, download=True)
        if not (directory / "audio.m4a").is_file():
            raise ValueError("Audio not downloaded")
        audio_path = "audio.m4a"
    return {"id": info["id"], "title": info["title"], "duration": info["duration"],
            "is_live": False, "audioFile": audio_path}


def transcribe(directory, model_path, device):
    dll_handles = []
    if device == "cuda" and os.name == "nt":
        for site_path in sys.path:
            for package in ("cublas", "cudnn", "cuda_nvrtc"):
                candidate = Path(site_path) / "nvidia" / package / "bin"
                if candidate.is_dir():
                    dll_handles.append(os.add_dll_directory(str(candidate)))
                    os.environ["PATH"] = str(candidate) + os.pathsep + os.environ.get("PATH", "")
    from faster_whisper import WhisperModel

    # Read only PCM generated by the offline decoder; never parse remote codecs here.
    import numpy as np
    with wave.open(str(Path(directory) / "audio.wav"), "rb") as audio:
        if audio.getnchannels() != 1 or audio.getsampwidth() != 2 or audio.getframerate() != 16000:
            raise ValueError("Expected mono 16kHz PCM")
        if not 0 < audio.getnframes() <= 1800 * 16000:
            raise ValueError("Unsupported audio length")
        samples = np.frombuffer(audio.readframes(audio.getnframes()), np.int16).astype(np.float32) / 32768
    model = WhisperModel(model_path, device=device, compute_type="float16" if device == "cuda" else "int8", cpu_threads=8, local_files_only=True)
    segments, _ = model.transcribe(samples, language="th", beam_size=3, vad_filter=True, condition_on_previous_text=False)
    output = []
    for segment in segments:
        text = segment.text.strip()
        start, end = round(segment.start * 1000), round(segment.end * 1000)
        if not text or end <= start or segment.no_speech_prob > 0.6:
            continue
        if output and len(output[-1]["text"]) + len(text) < 250 and start - output[-1]["endMs"] < 1500:
            output[-1]["text"] += " " + text
            output[-1]["endMs"] = end
        else:
            output.append({"startMs": start, "endMs": end, "text": text})
    return {"language": "th", "segments": output}


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("operation", choices=["download", "transcribe"])
    parser.add_argument("directory")
    parser.add_argument("value")
    parser.add_argument("--device", choices=["cpu", "cuda"], default="cpu")
    args = parser.parse_args()
    os.environ["HF_HUB_OFFLINE"] = "1"
    try:
        result = download(args.value, args.directory) if args.operation == "download" else transcribe(args.directory, args.value, args.device)
        print(json.dumps(result, ensure_ascii=True))
    except Exception:
        # Do not emit provider responses, URLs with signatures, credentials or paths.
        print(json.dumps({"error": args.operation + " failed"}))
        raise SystemExit(1)
